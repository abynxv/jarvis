"""
Unified LLM provider abstraction for JARVIS.
Supports Google Gemini, Ollama, OpenAI, and Anthropic behind one async interface
with normalized message schemas, token usage tracking, streaming, and error mapping.
"""
from __future__ import annotations

import asyncio
import math
from abc import ABC, abstractmethod
from typing import Any, AsyncGenerator, Literal, Optional, Sequence

import httpx
from pydantic import BaseModel, Field

from backend.app.core.config import Settings, get_settings

MessageRole = Literal["system", "user", "assistant", "tool"]


class ChatMessage(BaseModel):
    """Normalized conversation turn passed to any LLM provider."""

    role: MessageRole
    content: str


class TokenUsage(BaseModel):
    """Token accounting returned by an LLM call."""

    input_tokens: int = 0
    output_tokens: int = 0
    total_tokens: int = 0


class LLMResponse(BaseModel):
    """Normalized non-streaming response from an LLM provider."""

    content: str
    model: str
    provider: str
    usage: TokenUsage = Field(default_factory=TokenUsage)
    finish_reason: Optional[str] = None


class LLMError(Exception):
    """Base error for all LLM integration failures."""

    retryable: bool = False

    def __init__(self, message: str, *, retryable: Optional[bool] = None):
        super().__init__(message)
        if retryable is not None:
            self.retryable = retryable


class LLMConfigurationError(LLMError):
    """Raised when provider settings or API keys are missing/invalid."""

    retryable = False


class LLMRateLimitError(LLMError):
    """Raised when the upstream LLM provider throttles requests (HTTP 429)."""

    retryable = True


class LLMTimeoutError(LLMError):
    """Raised when an LLM request exceeds the configured timeout."""

    retryable = True


class LLMProviderError(LLMError):
    """Raised for upstream provider outages, network failures, or unexpected errors."""


def _split_system_prompt(
    messages: Sequence[ChatMessage],
    system_prompt: Optional[str] = None,
) -> tuple[Optional[str], list[ChatMessage]]:
    """Separate system messages from conversational turns while preserving order."""
    system_parts: list[str] = []
    if system_prompt:
        system_parts.append(system_prompt.strip())

    turns: list[ChatMessage] = []
    for msg in messages:
        if msg.role == "system":
            if msg.content.strip():
                system_parts.append(msg.content.strip())
        else:
            turns.append(msg)

    combined_system = "\n\n".join(system_parts) if system_parts else None
    return combined_system, turns


def _estimate_tokens(messages: Sequence[ChatMessage], system_prompt: Optional[str]) -> int:
    """Rough ~4-chars-per-token heuristic used when a provider lacks a token-count API."""
    total_chars = len(system_prompt or "") + sum(len(m.content) for m in messages)
    return max(1, math.ceil(total_chars / 4)) if total_chars else 0


class BaseLLMProvider(ABC):
    """Common async contract implemented by every LLM backend."""

    provider_name: str

    def __init__(self, settings: Settings):
        self.settings = settings
        self.model = settings.LLM_MODEL

    def _resolve_params(
        self,
        temperature: Optional[float],
        max_tokens: Optional[int],
    ) -> tuple[float, int]:
        return (
            self.settings.LLM_TEMPERATURE if temperature is None else temperature,
            self.settings.LLM_MAX_TOKENS if max_tokens is None else max_tokens,
        )

    @abstractmethod
    async def generate(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> LLMResponse:
        """Generate a complete response for the given conversation history."""

    @abstractmethod
    async def stream(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        """Yield text chunks as they are generated by the LLM."""

    async def count_tokens(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
    ) -> int:
        """Count (or estimate) input tokens for context-window budgeting."""
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        return _estimate_tokens(turns, combined_system)


class GeminiProvider(BaseLLMProvider):
    """Google Gemini provider via the official `google-genai` SDK."""

    provider_name = "gemini"

    def __init__(self, settings: Settings, client: Optional[Any] = None):
        super().__init__(settings)
        if client is not None:
            self._client = client
            return
        if not settings.GEMINI_API_KEY:
            raise LLMConfigurationError(
                "GEMINI_API_KEY is required when LLM_PROVIDER='gemini'."
            )
        from google import genai

        self._client = genai.Client(api_key=settings.GEMINI_API_KEY)

    @staticmethod
    def _to_genai_contents(turns: Sequence[ChatMessage]) -> list[Any]:
        from google.genai import types

        contents: list[types.Content] = []
        for msg in turns:
            # Gemini expects "model" rather than "assistant" for model turns.
            role = "model" if msg.role == "assistant" else "user"
            contents.append(
                types.Content(role=role, parts=[types.Part.from_text(text=msg.content)])
            )
        return contents

    @staticmethod
    def _build_config(
        system_instruction: Optional[str],
        temperature: float,
        max_tokens: int,
    ) -> Any:
        from google.genai import types

        return types.GenerateContentConfig(
            system_instruction=system_instruction,
            temperature=temperature,
            max_output_tokens=max_tokens,
        )

    @staticmethod
    def _map_exception(exc: Exception) -> LLMError:
        from google.genai import errors as genai_errors

        if isinstance(exc, LLMError):
            return exc
        if isinstance(exc, (TimeoutError, asyncio.TimeoutError, httpx.TimeoutException)):
            return LLMTimeoutError(f"Gemini request timed out: {exc}")
        if isinstance(exc, genai_errors.APIError):
            code = getattr(exc, "code", None)
            if code == 429:
                return LLMRateLimitError(f"Gemini rate limit exceeded: {exc}")
            if code in (401, 403):
                return LLMConfigurationError(f"Gemini authentication failed: {exc}")
            retryable = code is not None and code >= 500
            return LLMProviderError(f"Gemini API error ({code}): {exc}", retryable=retryable)
        return LLMProviderError(f"Gemini call failed: {exc}", retryable=False)

    async def generate(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> LLMResponse:
        temp, max_tok = self._resolve_params(temperature, max_tokens)
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        contents = self._to_genai_contents(turns)
        config = self._build_config(combined_system, temp, max_tok)

        try:
            response = await asyncio.wait_for(
                self._client.aio.models.generate_content(
                    model=self.model,
                    contents=contents,
                    config=config,
                ),
                timeout=self.settings.LLM_TIMEOUT_SECONDS,
            )
        except Exception as exc:
            raise self._map_exception(exc) from exc

        usage_meta = getattr(response, "usage_metadata", None)
        input_tokens = getattr(usage_meta, "prompt_token_count", 0) or 0
        output_tokens = getattr(usage_meta, "candidates_token_count", 0) or 0
        total_tokens = getattr(usage_meta, "total_token_count", 0) or (
            input_tokens + output_tokens
        )

        finish_reason = None
        candidates = getattr(response, "candidates", None) or []
        if candidates:
            raw_reason = getattr(candidates[0], "finish_reason", None)
            finish_reason = str(raw_reason) if raw_reason is not None else None

        return LLMResponse(
            content=getattr(response, "text", None) or "",
            model=self.model,
            provider=self.provider_name,
            usage=TokenUsage(
                input_tokens=input_tokens,
                output_tokens=output_tokens,
                total_tokens=total_tokens,
            ),
            finish_reason=finish_reason,
        )

    async def stream(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        temp, max_tok = self._resolve_params(temperature, max_tokens)
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        contents = self._to_genai_contents(turns)
        config = self._build_config(combined_system, temp, max_tok)

        try:
            response_stream = await asyncio.wait_for(
                self._client.aio.models.generate_content_stream(
                    model=self.model,
                    contents=contents,
                    config=config,
                ),
                timeout=self.settings.LLM_TIMEOUT_SECONDS,
            )
            async for chunk in response_stream:
                text = getattr(chunk, "text", None)
                if text:
                    yield text
        except Exception as exc:
            raise self._map_exception(exc) from exc

    async def count_tokens(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
    ) -> int:
        from google.genai import types

        combined_system, turns = _split_system_prompt(messages, system_prompt)
        contents = self._to_genai_contents(turns)
        config = (
            types.CountTokensConfig(system_instruction=combined_system)
            if combined_system
            else None
        )
        try:
            result = await asyncio.wait_for(
                self._client.aio.models.count_tokens(
                    model=self.model,
                    contents=contents,
                    config=config,
                ),
                timeout=self.settings.LLM_TIMEOUT_SECONDS,
            )
            return getattr(result, "total_tokens", 0) or 0
        except Exception as exc:
            raise self._map_exception(exc) from exc


class OllamaProvider(BaseLLMProvider):
    """Local Ollama provider via `ollama.AsyncClient`."""

    provider_name = "ollama"

    def __init__(self, settings: Settings, client: Optional[Any] = None):
        super().__init__(settings)
        if client is not None:
            self._client = client
            return
        import ollama

        self._client = ollama.AsyncClient(
            host=settings.OLLAMA_BASE_URL,
            timeout=settings.LLM_TIMEOUT_SECONDS,
        )

    @staticmethod
    def _to_ollama_messages(
        turns: Sequence[ChatMessage],
        combined_system: Optional[str],
    ) -> list[dict[str, str]]:
        payload: list[dict[str, str]] = []
        if combined_system:
            payload.append({"role": "system", "content": combined_system})
        for msg in turns:
            payload.append({"role": msg.role, "content": msg.content})
        return payload

    @staticmethod
    def _map_exception(exc: Exception) -> LLMError:
        if isinstance(exc, LLMError):
            return exc
        if isinstance(exc, (TimeoutError, asyncio.TimeoutError, httpx.TimeoutException)):
            return LLMTimeoutError(f"Ollama request timed out: {exc}")
        if isinstance(exc, httpx.ConnectError):
            return LLMProviderError(
                f"Cannot reach Ollama server: {exc}",
                retryable=True,
            )
        return LLMProviderError(f"Ollama call failed: {exc}", retryable=False)

    async def generate(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> LLMResponse:
        temp, max_tok = self._resolve_params(temperature, max_tokens)
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        payload = self._to_ollama_messages(turns, combined_system)

        try:
            response = await self._client.chat(
                model=self.model,
                messages=payload,
                stream=False,
                options={"temperature": temp, "num_predict": max_tok},
            )
        except Exception as exc:
            raise self._map_exception(exc) from exc

        message_obj = response.get("message", {}) if isinstance(response, dict) else getattr(response, "message", None)
        content = (
            message_obj.get("content", "")
            if isinstance(message_obj, dict)
            else getattr(message_obj, "content", "")
        ) or ""
        input_tokens = (
            response.get("prompt_eval_count", 0)
            if isinstance(response, dict)
            else getattr(response, "prompt_eval_count", 0)
        ) or 0
        output_tokens = (
            response.get("eval_count", 0)
            if isinstance(response, dict)
            else getattr(response, "eval_count", 0)
        ) or 0
        done_reason = (
            response.get("done_reason")
            if isinstance(response, dict)
            else getattr(response, "done_reason", None)
        )

        return LLMResponse(
            content=content,
            model=self.model,
            provider=self.provider_name,
            usage=TokenUsage(
                input_tokens=input_tokens,
                output_tokens=output_tokens,
                total_tokens=input_tokens + output_tokens,
            ),
            finish_reason=done_reason,
        )

    async def stream(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        temp, max_tok = self._resolve_params(temperature, max_tokens)
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        payload = self._to_ollama_messages(turns, combined_system)

        try:
            chunk_stream = await self._client.chat(
                model=self.model,
                messages=payload,
                stream=True,
                options={"temperature": temp, "num_predict": max_tok},
            )
            async for chunk in chunk_stream:
                msg = chunk.get("message", {}) if isinstance(chunk, dict) else getattr(chunk, "message", None)
                text = (
                    msg.get("content", "")
                    if isinstance(msg, dict)
                    else getattr(msg, "content", "")
                )
                if text:
                    yield text
        except Exception as exc:
            raise self._map_exception(exc) from exc


class OpenAIProvider(BaseLLMProvider):
    """OpenAI provider via `openai.AsyncOpenAI`."""

    provider_name = "openai"

    def __init__(self, settings: Settings, client: Optional[Any] = None):
        super().__init__(settings)
        if client is not None:
            self._client = client
            return
        if not settings.OPENAI_API_KEY:
            raise LLMConfigurationError(
                "OPENAI_API_KEY is required when LLM_PROVIDER='openai'."
            )
        from openai import AsyncOpenAI

        self._client = AsyncOpenAI(
            api_key=settings.OPENAI_API_KEY,
            timeout=settings.LLM_TIMEOUT_SECONDS,
        )

    @staticmethod
    def _to_openai_messages(
        turns: Sequence[ChatMessage],
        combined_system: Optional[str],
    ) -> list[dict[str, str]]:
        payload: list[dict[str, str]] = []
        if combined_system:
            payload.append({"role": "system", "content": combined_system})
        for msg in turns:
            payload.append({"role": msg.role, "content": msg.content})
        return payload

    @staticmethod
    def _map_exception(exc: Exception) -> LLMError:
        import openai

        if isinstance(exc, LLMError):
            return exc
        if isinstance(exc, (openai.APITimeoutError, TimeoutError, asyncio.TimeoutError)):
            return LLMTimeoutError(f"OpenAI request timed out: {exc}")
        if isinstance(exc, openai.RateLimitError):
            return LLMRateLimitError(f"OpenAI rate limit exceeded: {exc}")
        if isinstance(exc, openai.AuthenticationError):
            return LLMConfigurationError(f"OpenAI authentication failed: {exc}")
        if isinstance(exc, openai.APIError):
            return LLMProviderError(f"OpenAI API error: {exc}", retryable=True)
        return LLMProviderError(f"OpenAI call failed: {exc}", retryable=False)

    async def generate(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> LLMResponse:
        temp, max_tok = self._resolve_params(temperature, max_tokens)
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        payload = self._to_openai_messages(turns, combined_system)

        try:
            response = await self._client.chat.completions.create(
                model=self.model,
                messages=payload,
                temperature=temp,
                max_tokens=max_tok,
            )
        except Exception as exc:
            raise self._map_exception(exc) from exc

        choice = response.choices[0] if response.choices else None
        content = (choice.message.content if choice and choice.message else "") or ""
        usage = getattr(response, "usage", None)
        input_tokens = getattr(usage, "prompt_tokens", 0) or 0
        output_tokens = getattr(usage, "completion_tokens", 0) or 0
        total_tokens = getattr(usage, "total_tokens", 0) or (input_tokens + output_tokens)

        return LLMResponse(
            content=content,
            model=self.model,
            provider=self.provider_name,
            usage=TokenUsage(
                input_tokens=input_tokens,
                output_tokens=output_tokens,
                total_tokens=total_tokens,
            ),
            finish_reason=getattr(choice, "finish_reason", None) if choice else None,
        )

    async def stream(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        temp, max_tok = self._resolve_params(temperature, max_tokens)
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        payload = self._to_openai_messages(turns, combined_system)

        try:
            chunk_stream = await self._client.chat.completions.create(
                model=self.model,
                messages=payload,
                temperature=temp,
                max_tokens=max_tok,
                stream=True,
            )
            async for chunk in chunk_stream:
                if not chunk.choices:
                    continue
                delta = getattr(chunk.choices[0], "delta", None)
                text = getattr(delta, "content", None)
                if text:
                    yield text
        except Exception as exc:
            raise self._map_exception(exc) from exc


class AnthropicProvider(BaseLLMProvider):
    """Anthropic Claude provider via `anthropic.AsyncAnthropic`."""

    provider_name = "anthropic"

    def __init__(self, settings: Settings, client: Optional[Any] = None):
        super().__init__(settings)
        if client is not None:
            self._client = client
            return
        if not settings.ANTHROPIC_API_KEY:
            raise LLMConfigurationError(
                "ANTHROPIC_API_KEY is required when LLM_PROVIDER='anthropic'."
            )
        from anthropic import AsyncAnthropic

        self._client = AsyncAnthropic(
            api_key=settings.ANTHROPIC_API_KEY,
            timeout=settings.LLM_TIMEOUT_SECONDS,
        )

    @staticmethod
    def _to_anthropic_messages(turns: Sequence[ChatMessage]) -> list[dict[str, str]]:
        return [
            {
                "role": "assistant" if msg.role == "assistant" else "user",
                "content": msg.content,
            }
            for msg in turns
        ]

    @staticmethod
    def _map_exception(exc: Exception) -> LLMError:
        import anthropic

        if isinstance(exc, LLMError):
            return exc
        if isinstance(exc, (anthropic.APITimeoutError, TimeoutError, asyncio.TimeoutError)):
            return LLMTimeoutError(f"Anthropic request timed out: {exc}")
        if isinstance(exc, anthropic.RateLimitError):
            return LLMRateLimitError(f"Anthropic rate limit exceeded: {exc}")
        if isinstance(exc, anthropic.AuthenticationError):
            return LLMConfigurationError(f"Anthropic authentication failed: {exc}")
        if isinstance(exc, anthropic.APIError):
            return LLMProviderError(f"Anthropic API error: {exc}", retryable=True)
        return LLMProviderError(f"Anthropic call failed: {exc}", retryable=False)

    async def generate(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> LLMResponse:
        temp, max_tok = self._resolve_params(temperature, max_tokens)
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        payload = self._to_anthropic_messages(turns)

        kwargs: dict[str, Any] = {
            "model": self.model,
            "messages": payload,
            "temperature": temp,
            "max_tokens": max_tok,
        }
        if combined_system:
            kwargs["system"] = combined_system

        try:
            response = await self._client.messages.create(**kwargs)
        except Exception as exc:
            raise self._map_exception(exc) from exc

        text_parts = [
            getattr(block, "text", "")
            for block in getattr(response, "content", [])
            if getattr(block, "type", None) == "text"
        ]
        usage = getattr(response, "usage", None)
        input_tokens = getattr(usage, "input_tokens", 0) or 0
        output_tokens = getattr(usage, "output_tokens", 0) or 0

        return LLMResponse(
            content="".join(text_parts),
            model=self.model,
            provider=self.provider_name,
            usage=TokenUsage(
                input_tokens=input_tokens,
                output_tokens=output_tokens,
                total_tokens=input_tokens + output_tokens,
            ),
            finish_reason=getattr(response, "stop_reason", None),
        )

    async def stream(
        self,
        messages: Sequence[ChatMessage],
        *,
        system_prompt: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncGenerator[str, None]:
        temp, max_tok = self._resolve_params(temperature, max_tokens)
        combined_system, turns = _split_system_prompt(messages, system_prompt)
        payload = self._to_anthropic_messages(turns)

        kwargs: dict[str, Any] = {
            "model": self.model,
            "messages": payload,
            "temperature": temp,
            "max_tokens": max_tok,
        }
        if combined_system:
            kwargs["system"] = combined_system

        try:
            async with self._client.messages.stream(**kwargs) as event_stream:
                async for text in event_stream.text_stream:
                    if text:
                        yield text
        except Exception as exc:
            raise self._map_exception(exc) from exc


_PROVIDER_MAP: dict[str, type[BaseLLMProvider]] = {
    "gemini": GeminiProvider,
    "ollama": OllamaProvider,
    "openai": OpenAIProvider,
    "anthropic": AnthropicProvider,
}


def create_llm_client(settings: Optional[Settings] = None) -> BaseLLMProvider:
    """Instantiate the configured LLM provider from Settings."""
    resolved = settings or get_settings()
    provider_cls = _PROVIDER_MAP.get(resolved.LLM_PROVIDER)
    if provider_cls is None:
        raise LLMConfigurationError(f"Unsupported LLM_PROVIDER: {resolved.LLM_PROVIDER}")
    return provider_cls(resolved)

